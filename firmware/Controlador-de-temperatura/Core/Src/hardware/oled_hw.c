static void oled_draw_char(uint8_t c, uint8_t x, uint8_t page)
{
    if (c < 32 || c > 57) return;
    c -= 32;

    for (int col = 0; col < 6; col++) {
        if (x + col < OLED_WIDTH) {
            oled_buffer[page * OLED_WIDTH + x + col] = font6x8[c][col];
        }
    }
}

void oled_hw_print_num(int num, uint8_t page)
{
    char buf[12];
    snprintf(buf, sizeof(buf), "%d", num);

    for (int i = 0; buf[i] != '\0'; i++) {
        oled_draw_char(buf[i], i * 6, page);
    }
}

void oled_hw_print_float(float val, uint8_t page)
{
    char buf[12];
    snprintf(buf, sizeof(buf), "%.2f", val);

    for (int i = 0; buf[i] != '\0'; i++) {
        oled_draw_char(buf[i], i * 6, page);
    }
}